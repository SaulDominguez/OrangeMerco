window.onload = function () {
    const selectEstado = document.getElementById('Estado'),
        selectCiudad = document.getElementById('Ciudad'),
        selectSucursal = document.getElementById('Sucursal'),
        selects = document.querySelectorAll('select#Estado, select#Ciudad, select#Sucursal'),
        textDireccion = document.getElementById('Ubicacion'),
        noSucursal = document.getElementById('NoSucursal');

    selectCiudad.disabled = true;
    selectSucursal.disabled = true;

    selects.forEach((select) => {
        if (select.disabled == true) {
            select.computedStyleMap.cursor = 'auto';
        }
    });

    for (let Estado in ciudadEstadoSucursalInfo) {
        // console.log(Estado);
        selectEstado.options[selectEstado.options.length] = new Option(Estado, Estado);
    }

    // Estado change
    selectEstado.onchange = (e) => {
        selectCiudad.disabled = false;
        selectSucursal.disabled = true;

        selectCiudad.length = 1;
        selectSucursal.length = 1;

        for (let Ciudad in ciudadEstadoSucursalInfo[e.target.value]) {
            // console.log(Ciudad);
            selectCiudad.options[selectCiudad.options.length] = new Option(Ciudad, Ciudad);
        }
    };

    // Ciudad change
    selectCiudad.onchange = (e) => {
        selectSucursal.disabled = false;

        selectSucursal.length = 1;

        for (let Sucursal in ciudadEstadoSucursalInfo[selectEstado.value][e.target.value]) {
            // console.log(Sucursal);
            selectSucursal.options[selectSucursal.options.length] = new Option(Sucursal, Sucursal);
        }
    };

    // Sucursal change
    selectSucursal.onchange = (e) => {
        let NoSucursal =
            ciudadEstadoSucursalInfo[selectEstado.value][selectCiudad.value][e.target.value][1];
        noSucursal.setAttribute('value', NoSucursal);
        let Direccion =
            ciudadEstadoSucursalInfo[selectEstado.value][selectCiudad.value][e.target.value][0];
        textDireccion.innerHTML = Direccion;
    };
};
